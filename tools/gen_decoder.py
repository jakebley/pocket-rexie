"""Regenerate the tolerant Codable init(from:) in Shared/Pet.swift from its stored properties. Run after adding fields."""
import re, os
path = os.path.join(os.path.dirname(__file__), '..', 'Shared', 'Pet.swift')
s = open(path).read()
a = s.index('struct Pet: Codable')
b = s.index('    init(now: Date = Date()')
body = s[a:b]
fix = {'legacy': '[String]', 'dex': '[String]', 'events': '[PetEvent]'}
lines = []
for m in re.finditer(r'^    var (\w+)(?:: ([\w\[\]\?]+))?(?: = (.+))?$', body, re.M):
    name, typ, default = m.groups()
    if typ is None:
        d = default or ''
        typ = 'Bool' if d in ('true', 'false') else 'Int' if re.fullmatch(r'-?\d+', d) else 'String' if d.startswith('"') else fix.get(name)
    assert typ, (name, default)
    if typ.endswith('?'):
        lines.append(f"        {name} = try c.decodeIfPresent({typ[:-1]}.self, forKey: .{name})")
    else:
        lines.append(f"        if let v = try c.decodeIfPresent({typ}.self, forKey: .{name}) {{ {name} = v }}")
dec = '''    /// Tolerant decoding: a save written by an older version (missing newer fields) still loads,
    /// with defaults filling the gaps, instead of resetting the pet. Generated by tools/gen_decoder.py.
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let birthDate = try c.decodeIfPresent(Date.self, forKey: .birth) ?? Date()
        self.init(now: birthDate)
''' + "\n".join(lines) + '''
        if seed == 0 { seed = 1 }
    }

'''
i = s.index('    /// Tolerant decoding')
j = s.index('    // MARK: derived')
s = s[:i] + dec + s[j:]
open(path, 'w').write(s)
print(len(lines), 'fields')
