"""Emit expo-prototype/src/core/reactionsData.ts from tools/reactions.py. Usage: python3 tools/gen_reactions.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import spritegen
from familyset import all_species
import reactions as R

species_kind, missing = {}, set()
for fam, sid, (name, stage, blurb, rec) in all_species():
    arch = rec.get('arch') or rec.get('archetype')
    if stage == 1:
        kind = R.KIND_OF.get(arch, 'baby') if arch else 'baby'
    else:
        kind = R.KIND_OF.get(arch)
    if kind is None:
        missing.add((fam.FAMILY, arch)); kind = 'baby'
    species_kind[sid] = kind
if missing: raise SystemExit(f'archetypes without a reaction kind: {sorted(missing, key=str)}')
for k in set(species_kind.values()):
    if k not in R.KIND_LINES: raise SystemExit(f'missing KIND_LINES for {k}')
bad = [l for ls in list(R.KIND_LINES.values()) + list(R.CONTEXT.values()) + list(R.SPECIES_LINES.values()) for l in ls if '{n}' not in l and 'head' not in l.lower() and len(l) > 40]
data = {"kindOf": species_kind, "kindLines": R.KIND_LINES, "context": R.CONTEXT, "speciesLines": {k: v for k, v in R.SPECIES_LINES.items() if v}}
path = os.path.join(os.path.dirname(__file__), '..', 'expo-prototype', 'src', 'core', 'reactionsData.ts')
with open(path, 'w') as f:
    f.write('// GENERATED by tools/gen_reactions.py from tools/reactions.py. Do not edit by hand.\n')
    f.write('export const REACTIONS = ' + json.dumps(data, indent=1) + ' as const;\n')
print('species with a kind:', len(species_kind), 'kinds:', len(set(species_kind.values())))
