import { FONT5X7 } from '../expo-prototype/src/ui/font5x7';
import { ICONS16 } from '../expo-prototype/src/ui/icons16';
import { writeFileSync } from 'fs';
import { resolve } from 'path';
// Technicolor interface chrome data (docs/RESOLUTION.md "Interface chrome") -> Shared/Chrome96Data.swift and Tests/Chrome96Golden.swift.
// Glyphs and icons are one string per entry (rows joined with '|'), parsed once at run time; never nested array literals (they hung the compiler).
// Run: cd expo-prototype && npx tsx ../tools/gen_chrome96.ts
const fnv = (s: string) => { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; } return h.toString(16); };
const root = resolve(__dirname, '..');
const fontLines = Object.entries(FONT5X7).map(([ch, rows]) => `${ch.charCodeAt(0).toString(16).padStart(2, '0')} ${rows.join('|')}`);
const iconLines = Object.entries(ICONS16).map(([n, rows]) => `${n} ${rows.join('|')}`);
const data = `// GENERATED by tools/gen_chrome96.ts from expo-prototype/src/ui/font5x7.ts and icons16.ts. Do not edit.
// One line per glyph ("hex codepoint rows|joined") or icon ("name rows|joined"); parsed by Chrome96 at first use.

enum Chrome96Data {
    static let font5x7 = """
${fontLines.join('\n')}
"""

    static let icons16 = """
${iconLines.join('\n')}
"""
}
`;
writeFileSync(`${root}/Shared/Chrome96Data.swift`, data);
const gold = `// GENERATED by tools/gen_chrome96.ts: FNV-1a 32 of every 5x7 glyph and 16x16 icon (rows joined with '|') as the Expo build has them.

enum Chrome96Golden {
    static let font = """
${Object.entries(FONT5X7).map(([ch, r]) => `${ch.charCodeAt(0).toString(16).padStart(2, '0')} ${fnv(r.join('|'))}`).join('\n')}
"""

    static let icons = """
${Object.entries(ICONS16).map(([n, r]) => `${n} ${fnv(r.join('|'))}`).join('\n')}
"""
}
`;
writeFileSync(`${root}/Tests/Chrome96Golden.swift`, gold);
console.log(`font ${fontLines.length} glyphs, ${iconLines.length} icons`);
