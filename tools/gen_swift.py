"""Emit Shared/SpeciesData.swift from species.py + spritegen.py. Usage: python3 tools/gen_swift.py"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from species import SPECIES, EVO, BABIES
import spritegen

STAGE = {1: '.baby', 2: '.child', 3: '.teen', 4: '.adult', 5: '.ultimate'}
out = ["// GENERATED by tools/gen_swift.py from tools/species.py. Do not edit by hand.", "import Foundation", "",
       "enum SpeciesData {", "    static let all: [Species] = ["]
for sid, (name, stage, blurb, rec) in SPECIES.items():
    a, b = spritegen.render(dict(rec, stage=stage))
    evo = []
    for child, req in EVO.get(sid, []):
        parts = []
        for k, v in req.items():
            if k == 'lead': parts.append(f"lead: .{v}")
            elif k == 'heavy': parts.append("heavy: true")
            else:
                swift = {'mist_min': 'mistMin', 'mist_max': 'mistMax'}.get(k, k)
                parts.append(f"{swift}: {v}")
        evo.append(f'            Evolution(to: "{child}", req: Requirement({", ".join(parts)}))')
    out.append(f'        Species(id: "{sid}", name: "{name}", stage: {STAGE[stage]}, blurb: "{blurb}",')
    out.append('            frames: [')
    out.append('                [' + ", ".join(f'"{r}"' for r in a) + '],')
    out.append('                [' + ", ".join(f'"{r}"' for r in b) + '],')
    out.append('            ],')
    out.append('            evolutions: [' + ("\n" + ",\n".join(evo) + "\n        " if evo else "") + ']),')
out.append("    ]")
out.append("")
out.append("    static let babies: [String] = [" + ", ".join(f'"{b}"' for b in BABIES) + "]")
out.append("}")
path = os.path.join(os.path.dirname(__file__), "..", "Shared", "SpeciesData.swift")
open(path, "w").write("\n".join(out) + "\n")
print("species:", len(SPECIES))
