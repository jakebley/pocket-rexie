"""Emit Shared/SpeciesData.swift from every family in tools/familyset.py + spritegen.py. Usage: python3 tools/gen_swift.py"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import spritegen
from familyset import FAMILIES, all_species
import speciescolor

# Per-species Technicolor body colour (same helper as gen_ts.py); dino has no LINE_COLORS and keeps PetLine.
BODY = speciescolor.body_colors([(f, sid, rec[1]) for f, sid, rec in all_species()])

STAGE = {1: '.baby', 2: '.child', 3: '.teen', 4: '.adult', 5: '.ultimate'}
out = ["// GENERATED by tools/gen_swift.py from tools/species.py and tools/families/*.py. Do not edit by hand.", "import Foundation", "",
       "enum SpeciesData {",
       "    /// Sprite rows are stored as one string per frame ('/' between rows): 400 species of nested array literals made the Swift compiler stall.",
       "    private static func rows(_ s: String) -> [String] { s.split(separator: \"/\").map(String.init) }", ""]
cur = None
for fam, sid, (name, stage, blurb, rec) in all_species():
    if fam.FAMILY != cur:
        if cur is not None: out.append("    ]"); out.append("")
        cur = fam.FAMILY
        out.append(f"    static let species_{cur}: [Species] = [")
    EVO, LINE, FAMILY = fam.EVO, fam.LINE, fam.FAMILY
    a, b = spritegen.render(dict(rec, stage=stage))
    evo = []
    for child, req in EVO.get(sid, []):
        parts = []
        ORDER = ['mist_min', 'mist_max', 'train', 'wins', 'smarts', 'disc', 'heavy', 'lead']  # Swift memberwise order
        for k, v in sorted(req.items(), key=lambda kv: ORDER.index(kv[0]) if kv[0] in ORDER else 99):
            if k == 'lead': parts.append(f"lead: .{v}")
            elif k == 'heavy': parts.append("heavy: true")
            else:
                swift = {'mist_min': 'mistMin', 'mist_max': 'mistMax'}.get(k, k)
                parts.append(f"{swift}: {v}")
        evo.append(f'            Evolution(to: "{child}", req: Requirement({", ".join(parts)}))')
    out.append(f'        Species(id: "{sid}", name: "{name}", stage: {STAGE[stage]}, blurb: "{blurb}", family: "{FAMILY}", line: "{LINE[sid]}", bodyHex: {'"%s"' % BODY[sid] if sid in BODY else 'nil'},')
    out.append(f'            frames: [rows("{"/".join(a)}"), rows("{"/".join(b)}")],')
    hi_a, hi_b = spritegen.scale2x(a, FAMILY == 'fox'), spritegen.scale2x(b, FAMILY == 'fox')
    out.append(f'            hiFrames: [rows("{"/".join(hi_a)}"), rows("{"/".join(hi_b)}")],')
    out.append('            evolutions: [' + ("\n" + ",\n".join(evo) + "\n        " if evo else "") + ']),')
out.append("    ]")
out.append("")
out.append("    static let all: [Species] = " + " + ".join(f"species_{f.FAMILY}" for f in FAMILIES))
out.append("")
babies = [b for fam in FAMILIES for b in fam.BABIES]
out.append("    static let babies: [String] = [" + ", ".join(f'"{b}"' for b in babies) + "]")
out.append("")
out.append("    /// Families in display order; the first is free and the default.")
out.append("    static let families: [Family] = [")
for fam in FAMILIES:
    foods = ", ".join(f'"{fam.FOOD_LABELS[k]}"' for k in ("meat", "veggie", "pasta"))
    out.append(f'        Family(id: "{fam.FAMILY}", name: "{fam.NAME}", isFree: {"true" if fam.IS_FREE else "false"}, foods: [{foods}]),')
out.append("    ]")
out.append("}")
path = os.path.join(os.path.dirname(__file__), "..", "Shared", "SpeciesData.swift")
open(path, "w").write("\n".join(out) + "\n")
print("species:", len(all_species()), "families:", [f.FAMILY for f in FAMILIES])
