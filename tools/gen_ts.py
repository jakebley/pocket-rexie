"""Emit expo-prototype/src/core/speciesData.ts from species.py + spritegen.py. Usage: python3 tools/gen_ts.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from species import SPECIES, EVO, BABIES
import spritegen

STAGE = {1: 'baby', 2: 'child', 3: 'teen', 4: 'adult', 5: 'ultimate'}
out = []
for sid, (name, stage, blurb, rec) in SPECIES.items():
    a, b = spritegen.render(dict(rec, stage=stage))
    evo = [{"to": c, "req": r} for c, r in EVO.get(sid, [])]
    out.append({"id": sid, "name": name, "stage": STAGE[stage], "blurb": blurb, "frames": [a, b], "evolutions": evo})
path = os.path.join(os.path.dirname(__file__), "..", "expo-prototype", "src", "core", "speciesData.ts")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w") as f:
    f.write("// GENERATED by tools/gen_ts.py. Do not edit by hand.\n")
    f.write("import type { SpeciesDef } from './types';\n\n")
    f.write("export const SPECIES: SpeciesDef[] = " + json.dumps(out, indent=1) + ";\n\n")
    f.write("export const BABIES: string[] = " + json.dumps(BABIES) + ";\n")
print("species:", len(out))
