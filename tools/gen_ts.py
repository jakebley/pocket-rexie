"""Emit expo-prototype/src/core/speciesData.ts from every family in tools/familyset.py + spritegen.py. Usage: python3 tools/gen_ts.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import spritegen
from familyset import FAMILIES, all_species

STAGE = {1: 'baby', 2: 'child', 3: 'teen', 4: 'adult', 5: 'ultimate'}
out = []
for fam, sid, (name, stage, blurb, rec) in all_species():
    EVO, LINE, FAMILY = fam.EVO, fam.LINE, fam.FAMILY
    a, b = spritegen.render(dict(rec, stage=stage))
    evo = [{"to": c, "req": r} for c, r in EVO.get(sid, [])]
    entry = {"id": sid, "name": name, "stage": STAGE[stage], "blurb": blurb, "family": FAMILY, "line": LINE[sid]}
    # Technicolor body colour per family: line names collide across families (hunter/stray/baby), so the hex travels with the species.
    colors = getattr(fam, "LINE_COLORS", None)
    if colors:
        entry["bodyHex"] = colors[LINE[sid]]
    entry.update({"frames": [a, b], "hiFrames": [spritegen.scale2x(a), spritegen.scale2x(b)], "evolutions": evo})
    out.append(entry)
path = os.path.join(os.path.dirname(__file__), "..", "expo-prototype", "src", "core", "speciesData.ts")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w") as f:
    f.write("// GENERATED by tools/gen_ts.py. Do not edit by hand.\n")
    f.write("import type { FamilyDef, SpeciesDef } from './types';\n\n")
    f.write("export const SPECIES: SpeciesDef[] = " + json.dumps(out, indent=1) + ";\n\n")
    f.write("export const BABIES: string[] = " + json.dumps([b for fam in FAMILIES for b in fam.BABIES]) + ";\n\n")
    fams = [{"id": fam.FAMILY, "name": fam.NAME, "isFree": fam.IS_FREE, "foods": [fam.FOOD_LABELS[k] for k in ("meat", "veggie", "pasta")]} for fam in FAMILIES]
    f.write("export const FAMILIES: FamilyDef[] = " + json.dumps(fams, indent=1) + ";\n")
print("species:", len(out), "families:", [f.FAMILY for f in FAMILIES])
