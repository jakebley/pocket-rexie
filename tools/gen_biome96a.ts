// Generates Shared/Biome96AData.swift: the static layers of the 96x96 biome painters A (meadow, woods, underwater, clouds, garden, yard,
// warren) and their slot colours, by running the Expo painters (expo-prototype/src/ui/biome96/*.ts) on a recording buffer.
// The static art is exported as run-length strings (compact, fast to compile); the animated parts are ported by hand in Biome96A*.swift.
// Run:  cd expo-prototype && npx tsx ../tools/gen_biome96a.ts
import { writeFileSync } from 'node:fs';
import { forceSpecies, newPet } from '../expo-prototype/src/core/pet';
import { BIOME96 } from '../expo-prototype/src/ui/biome96';
import { A_FIRST, A_LAST, CLOUDS, MEADOW, WATER, WOODS, YARD, biomeAColors } from '../expo-prototype/src/ui/biome96/colorsA';
import type { Biome } from '../expo-prototype/src/ui/biomes';
import { Buf } from '../expo-prototype/src/ui/pixel';
import { TICK_MS, initScene, type Phase } from '../expo-prototype/src/ui/scene';

const N = 96;
/** Swift slot codes are the Expo ones + 3 (the egg shell owns 95...97 in the Swift SceneLayer). */
const SHIFT = 3;
const T0 = 1_800_000_000_000 - (1_800_000_000_000 % TICK_MS);
const PHASES: Phase[] = ['dawn', 'day', 'dusk', 'night'];
const SET: Biome[] = ['meadow', 'woods', 'underwater', 'clouds', 'garden', 'yard', 'warren'];

/** A buffer whose set() goes to an overlay: what is left in px is what the cached static layers blitted. */
class Rec extends Buf {
  live = new Uint8Array(N * N);
  set(x: number, y: number, v: number = this.cur) { if (x >= 0 && y >= 0 && x < this.n && y < this.n) this.live[y * this.n + x] = v; }
}
const pet = newPet(T0, { seed: 7 }); forceSpecies(pet, 'chomper'); pet.named = true;
function grab(biome: Biome, part: 'backdrop' | 'fore', phase: Phase, rain: boolean, nowMs: number, still: boolean): Uint8Array {
  const b = new Rec(N);
  const s = { ...initScene(pet, T0, 12), still, nowMs, hour: 12, minute: 0 };
  const c = { b, s, phase, rain, biome, g: (v: number) => Math.round(v * 1.5) } as never;
  BIOME96[biome]![part]!(c);
  return b.px;
}
const shift = (px: Uint8Array) => px.map((v) => (v >= A_FIRST ? v + SHIFT : v));
function rle(px: Uint8Array): string {
  const out: string[] = [];
  for (let i = 0; i < px.length;) { let j = i; while (j < px.length && px[j] === px[i]) j++; out.push(`${px[i].toString(16)}x${j - i}`); i = j; }
  return out.join(',');
}
const grids: string[] = []; const ids = new Map<string, number>(); const keys: string[] = [];
const hashes: string[] = [];
function add(key: string, px: Uint8Array) {
  if (!px.some((v) => v)) return; // empty layers are not stored
  const s = rle(shift(px));
  let id = ids.get(s);
  if (id === undefined) { id = grids.length; grids.push(s); ids.set(s, id); }
  keys.push(`${key}=${id}`);
}
const fnv = (px: Uint8Array) => { let h = 0x811c9dc5; for (const v of px) { h ^= v; h = Math.imul(h, 0x01000193) >>> 0; } return h; };

for (const biome of SET) for (const phase of PHASES) for (const rain of [false, true]) {
  const k = `${biome}.${phase}.${rain ? 1 : 0}`;
  const back = grab(biome, 'backdrop', phase, rain, T0, true);
  add(`${k}.back`, back);
  add(`${k}.fore`, grab(biome, 'fore', phase, rain, T0, true));
  if (biome === 'underwater') {
    // the light shafts shimmer in four steps (the clock picks floor(ms / 900) % 4): the full back layer of steps 1..3 is stored too
    for (let step = 1; step < 4; step++) add(`${k}.back${step}`, grab(biome, 'backdrop', phase, rain, 900 * (1000 + step) + 1, false));
  }
  hashes.push(`${k}.back=${fnv(shift(back)).toString(16)}`);
}

// slot colours: per biome, phase and rain, the resolved hex of codes A_FIRST..A_LAST (empty where the biome has no slot)
const colors: string[] = [];
for (const biome of SET) for (const phase of PHASES) for (const rain of [false, true]) {
  const t = biomeAColors(biome, phase, rain);
  if (!t) continue;
  const row: string[] = [];
  for (let l = A_FIRST; l <= A_LAST; l++) row.push(t[l] ? t[l].slice(1) : '-');
  while (row.length && row[row.length - 1] === '-') row.pop();
  colors.push(`${biome}.${phase}.${rain ? 1 : 0}=${row.join(',')}`);
}

const slotEnum = (name: string, c: Record<string, number>) =>
  `    enum ${name} {\n${Object.entries(c).map(([k, v]) => `        static let ${k}: UInt8 = ${v + SHIFT}`).join('\n')}\n    }`;
const slots = [slotEnum('Meadow', MEADOW.c), slotEnum('Woods', WOODS.c), slotEnum('Water', WATER.c), slotEnum('Clouds', CLOUDS.c), slotEnum('Yard', YARD.c)].join('\n');
const q = (s: string) => `"${s}"`;
const src = `// GENERATED by tools/gen_biome96a.ts from expo-prototype/src/ui/biome96 (do not edit). Static layers of the 96x96 biome painters A as
// run-length strings ("<code hex>x<run>,..." over 96x96 cells, row by row), the slot colours, and the layer hashes the tests pin.
enum Biome96AData {
    /// "biome.phase.rain.part=gridIndex" lines
    static let index: String = """
${keys.join('\n')}
"""

    /// "biome.phase.rain=RRGGBB,..." slot colours, the first entry is slot code \`Slot96.first\`
    static let colors: String = """
${colors.join('\n')}
"""

    /// "biome.phase.rain.part=FNV-1a of the decoded layer" (Expo backdrop layers, shifted slot codes)
    static let hashes: String = """
${hashes.join('\n')}
"""

    /// Slot codes by biome (names as in expo-prototype/src/ui/biome96/colorsA.ts)
    enum Slot {
${slots}
    }

    static let grids: [String] = [
${grids.map((g) => `        ${q(g)},`).join('\n')}
    ]
}
`;
writeFileSync(new URL('../Shared/Biome96AData.swift', import.meta.url), src);
console.log(`grids ${grids.length}, keys ${keys.length}, bytes ${src.length}`);
